fruits = ["apple", "banana", "cherry"]
print ("fruit in fruits :-")

for fruit in fruits:
    print(fruit)

# You can also specify a start, stop, and step value: range(start, stop, step).

print("Starts at 1, stops before 10, jumps by 2 :-")

for i in range(1, 10, 2):   # Print: 1, 3, 5, 7, 9
    print(i) 