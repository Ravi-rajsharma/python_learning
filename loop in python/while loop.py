# while loop example

print("range of 3 skip of 1 :- ")

count = 1
while count <= 3:
    print(count)
    count += 1  # Crucial: updates the condition to prevent an infinite loop

print("range of 3 skip of 2 :- ")

count = 1
while count <= 3:
    print(count)
    count += 2  # Crucial: updates the condition to prevent an infinite loop